const INSET_CAVEAT =
  'Android window insets depend on OEM skin, OS version and the user\'s navigation setting; treat these values as representative defaults rather than guarantees.';

function toRaw(spec: AndroidSpec, navMode: 'android-gesture' | 'android-three-button'): RawDeviceRecord {
  const [w, h] = spec.logical;
  const gesture = navMode === 'android-gesture';
  const bottomInset = gesture ? spec.gestureInset : 48;
  return {
    id: gesture ? spec.id : `${spec.id}-3button`,
    manufacturer: spec.manufacturer,
    family: spec.family,
    model: spec.model,
    marketingName: gesture ? spec.marketingName : `${spec.marketingName} (3-button nav)`,
    platform: 'android',
    osName: 'Android',
    osMin: spec.osMin,
    releaseYear: spec.year,
    generation: spec.generation,
    screenSizeInches: spec.inches,

    logicalWidth: w,
    logicalHeight: h,
    physicalWidth: spec.physical[0],
    physicalHeight: spec.physical[1],
    devicePixelRatio: spec.dpr,
    ppi: spec.ppi,
    densityBucket: spec.bucket,

    safeTop: spec.statusBar,
    safeBottom: bottomInset,
    safeLeft: 0,
    safeRight: 0,
    statusBarHeight: spec.statusBar,
    statusBarOverlaysContent: true,

    cutoutKind: spec.cutout,
    cutoutWidth: spec.cutoutBox[0],
    cutoutHeight: spec.cutoutBox[1],
    cutoutTop: spec.cutoutBox[2],
    cutoutRadius: spec.cutoutBox[0] / 2,

    navMode,
    navHeight: bottomInset,
    indicatorWidth: gesture ? 108 : 0,

    screenCornerRadius: spec.cornerRadius,

    keyboardSupported: true,
    keyboardHeight: spec.keyboardHeight,
    keyboardAccessoryHeight: 0,

    landscape: {
      width: h,
      height: w,
      safeTop: 0,
      safeBottom: gesture ? 16 : 48,
      safeLeft: 0,
      safeRight: 0,
    },

    ...ANDROID_CONVENTIONS,

    sources: {
      identity: 'oem-spec',
      viewport: 'oem-spec',
      physical: 'oem-spec',
      safeArea: 'android-docs',
      cutout: 'android-docs',
      navigation: 'android-docs',
      cornerRadius: 'community-dataset',
      keyboard: 'community-dataset',
      conventions: 'android-docs',
    },
    confidence: {
      viewport: 'high',
      physical: 'high',
      safeArea: 'medium',
      cutout: 'medium',
      navigation: 'medium',
      cornerRadius: 'low',
      keyboard: 'low',
    },
    references: {
      safeArea: 'https://developer.android.com/develop/ui/views/layout/edge-to-edge',
      cutout: 'https://developer.android.com/develop/ui/views/layout/display-cutout',
      navigation: 'https://developer.android.com/develop/ui/views/layout/insets',
      conventions: 'https://m3.material.io/foundations/layout/understanding-layout/overview',
    },
    caveats: [
      INSET_CAVEAT,
      'Software keyboard height varies by IME (Gboard, Samsung Keyboard, ...); the catalog value is a representative Gboard portrait height.',
    ],
  };
}

export const androidProvider: DeviceDataProvider = {
  id: 'android',
  name: 'Android developer documentation + OEM specifications',
  url: 'https://developer.android.com/develop/ui/views/layout/insets',
  license: 'Referenced documentation; no data files redistributed.',
  precedence: 90,
  fetch: () => [
    ...PHONES.map((spec) => toRaw(spec, 'android-gesture')),
    // A three-button-navigation variant for the two most common test targets,
    // since the 48dp bottom inset materially changes bottom-bar clearance.
    toRaw(PHONES[1]!, 'android-three-button'),
    toRaw(PHONES[9]!, 'android-three-button'),
  ],
};
