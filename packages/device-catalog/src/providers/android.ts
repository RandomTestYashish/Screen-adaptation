/**
 * Android device geometry.
 *
 * Physical resolution and display density come from manufacturer product
 * specifications. Window-inset behaviour (status bar, gesture navigation,
 * display cutouts, density buckets) follows the Android developer
 * documentation on WindowInsets and DisplayCutout.
 *
 * Android insets are genuinely device- and OEM-skin-dependent and can change
 * with an OS update, so every inset here is carried at `medium` confidence
 * with an explicit caveat rather than being presented as exact.
 */

